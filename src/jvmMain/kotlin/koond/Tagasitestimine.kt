/**
 * Küsitluste koondmudeli tagasitestimine (vt docs/kusitluste-koond.md). Kirjutab aruande ja lõplikud
 * parameetrid. Käivitamine: ./gradlew tagasitest
 */
fun main(args: Array<String>) {
  require(args.size == 2) { "Kasutamine: TagasitestimineKt <aruanne.md> <parameetrid.json>" }
  val lugeja = AndmeFailideLugeja()
  val tulemus = tagasitesti(loeValimised(lugeja), lugeja)
  File(args[0]).writeText(tulemus.aruanne)
  File(args[1]).writeText(tulemus.parameetridJson)
}

/** valimiste kuupäevad */
val VALIMISTE_KUUPÄEVAD = mapOf(
  2011 to LocalDate.parse("2011-03-06"),
  2015 to LocalDate.parse("2015-03-01"),
  2019 to LocalDate.parse("2019-03-03"),
  2023 to LocalDate.parse("2023-03-05"),
)

/** tagasitestimise horisondid päevades enne valimisi */
val HORISONDID = listOf(3L, 30L, 90L)

/** Loeb valimised, mille küsitluste fail on olemas. */
fun loeValimised(lugeja: AndmeFailideLugeja): List<Valimised> {
  val tulemused = lugeja.loeRessurss("kusitlused/tulemused.csv").lines().drop(1).filter { it.isNotBlank() }
    .map { it.split(",") }
    .groupBy({ it[0].trim().toInt() }, { it[1].trim() to it[2].trim().toDouble() })
  return VALIMISTE_KUUPÄEVAD.mapNotNull { (aasta, kuupäev) ->
    val csv = runCatching { lugeja.loeRessurss("kusitlused/rk$aasta.csv") }.getOrNull() ?: return@mapNotNull null
    val küsitlused = loeKüsitlused(csv)
    if (küsitlused.isEmpty()) null
    else Valimised(aasta, kuupäev, tulemused[aasta]!!.toMap(), küsitlused)
  }
}

data class Tagasitest(val aruanne: String, val parameetridJson: String)

private fun f(x: Double, kohti: Int = 2) = String.format(Locale.ROOT, "%.${kohti}f", x)

fun tagasitesti(valimised: List<Valimised>, lugeja: AndmeFailideLugeja? = null): Tagasitest {
  val r = StringBuilder()
  r.appendLine("> **Note on AI authorship.** This report was generated by a program written by AI (Claude by")
  r.appendLine("> Anthropic, in Claude Code); the surrounding text was written by AI as well.")
  r.appendLine()
  r.appendLine("# Poll aggregation backtest")
  r.appendLine()
  r.appendLine("Generated by `./gradlew tagasitest` from `src/jvmMain/resources/kusitlused/`. The model choices and")
  r.appendLine("the adoption criteria were fixed beforehand in `docs/kusitluste-koond.md`. Error sizes are standard")
  r.appendLine("deviations on the log scale: 0.10 means a typical relative error of about 10%.")
  r.appendLine()

  // andmed
  r.appendLine("## Data")
  r.appendLine()
  r.appendLine("| Election | Polls | Pollsters (polls) | Rows summing outside 95–105 before \"others\" is filled in |")
  r.appendLine("|---|---|---|---|")
  for (v in valimised) {
    val küsitlejad = v.küsitlused.groupingBy { it.küsitleja }.eachCount().entries.sortedByDescending { it.value }
      .joinToString(", ") { "${it.key} (${it.value})" }
    val kõrvalised = v.küsitlused.count { it.algneSumma < 95.0 || it.algneSumma > 105.0 }
    r.appendLine("| ${v.aasta} | ${v.küsitlused.size} | $küsitlejad | $kõrvalised |")
  }
  r.appendLine()

  // jäta-üks-välja hinnangud
  data class Rida(val aasta: Int, val horisont: Long, val meetod: Meetod, val skoor: Skoor)
  val read = mutableListOf<Rida>()
  val looParameetrid = mutableMapOf<Pair<Int, Long>, Mudeliparameetrid>()
  for (h in HORISONDID) {
    for (v in valimised) {
      val teised = valimised.filter { it.aasta != v.aasta }
      val p = hindaParameetrid(teised, h)
      looParameetrid[v.aasta to h] = p
      for (meetod in Meetod.entries) {
        val hinnang = hinnang(v.küsitlused, v.kuupäev.minusDays(h), meetod, p) ?: continue
        read.add(Rida(v.aasta, h, meetod, skoor(hinnang, v.tulemus)))
      }
    }
  }

  r.appendLine("## Leave-one-out parameters")
  r.appendLine()
  r.appendLine("Estimated from the other elections; the value for an election is the one used to forecast it.")
  r.appendLine()
  r.appendLine("| Horizon | Election | Common error | House effect (pooled) | House effect by pollster |")
  r.appendLine("|---|---|---|---|---|")
  for (h in HORISONDID) for (v in valimised) {
    val p = looParameetrid[v.aasta to h]!!
    val küsitlejad = p.küsitlejateMajaefekt.entries.sortedBy { it.key }.joinToString(", ") { "${it.key} ${f(sqrt(it.value))}" }
    r.appendLine("| $h d | ${v.aasta} | ${f(sqrt(p.ühine))} | ${f(sqrt(p.majaefekt))} | $küsitlejad |")
  }
  r.appendLine()

  r.appendLine("## Results")
  r.appendLine()
  r.appendLine("Mean absolute error (MAE) in percentage points over parties with a result of at least 3%, averaged")
  r.appendLine("over elections; coverage of the 90% interval as counts; mean log score per party (higher is better).")
  r.appendLine()
  for (h in HORISONDID) {
    r.appendLine("### $h days before the election")
    r.appendLine()
    r.appendLine("| Method | " + valimised.joinToString(" | ") { "MAE ${it.aasta}" } + " | Mean MAE | 90% coverage | Log score |")
    r.appendLine("|---|" + valimised.joinToString("") { "---|" } + "---|---|---|")
    for (meetod in Meetod.entries) {
      val meetodiRead = read.filter { it.horisont == h && it.meetod == meetod }
      if (meetodiRead.isEmpty()) continue
      val mae = valimised.map { v -> meetodiRead.find { it.aasta == v.aasta }?.skoor?.keskmineAbsViga }
      val kokku = meetodiRead.map { it.skoor }.reduce(Skoor::plus)
      val keskmine = mae.filterNotNull().average()
      r.appendLine("| ${meetod.kirjeldus} | " + mae.joinToString(" | ") { it?.let { x -> f(x) } ?: "–" } +
        " | ${f(keskmine)} (${mae.count { it != null }} el.) | ${kokku.kaetud} / ${kokku.erakondi} | ${f(kokku.logSkoor / kokku.erakondi)} |")
    }
    r.appendLine()
  }

  // otsused eelnevalt kirja pandud kriteeriumide järgi
  fun keskmineMae(h: Long, meetod: Meetod): Double? =
    read.filter { it.horisont == h && it.meetod == meetod }.map { it.skoor.keskmineAbsViga }.takeIf { it.isNotEmpty() }?.average()
  fun katvus(h: Long, meetod: Meetod): Skoor =
    read.filter { it.horisont == h && it.meetod == meetod }.map { it.skoor }.reduce(Skoor::plus)

  val usaldus3 = keskmineMae(3, Meetod.USALDUSKAALUD)
  val võrdsed3 = keskmineMae(3, Meetod.VÕRDSED_KAALUD)
  val valitud = if (usaldus3 != null && võrdsed3 != null && usaldus3 < võrdsed3) Meetod.USALDUSKAALUD else Meetod.VÕRDSED_KAALUD
  val valitudKatvus = katvus(3, valitud)
  val katvuseOsakaal = valitudKatvus.kaetud.toDouble() / valitudKatvus.erakondi
  val vigaKehtib = katvuseOsakaal in 0.80..0.98

  r.appendLine("## Decisions under the criteria fixed beforehand")
  r.appendLine()
  r.appendLine("- Trust weights against equal weights at the 3-day horizon: mean MAE ${usaldus3?.let { f(it) }} against " +
    "${võrdsed3?.let { f(it) }}. The chosen method is **${valitud.kirjeldus}**.")
  r.appendLine("- Coverage of the chosen method's 90% intervals at the 3-day horizon: ${valitudKatvus.kaetud} of " +
    "${valitudKatvus.erakondi} (${f(katvuseOsakaal * 100, 0)}%). The criterion (80–98%) is " +
    (if (vigaKehtib) "met, so the leave-one-out common error replaces the in-sample value." else "not met, so the error model failed this test; the larger of the two values is used."))
  r.appendLine()

  // korrelatsioonide katse valitud meetodiga: standardiseeritud vead erakondadele, kes on vähemalt kolmel valimisel
  val vaatlused = mutableMapOf<Int, MutableList<Vead>>()
  for (h in HORISONDID) for (v in valimised) {
    val hinnang = hinnang(v.küsitlused, v.kuupäev.minusDays(h), valitud, looParameetrid[v.aasta to h]!!) ?: continue
    val vead = v.tulemus.filter { (e, t) -> t >= HINNATAVA_PIIR && e in hinnang.logKeskmine }
      .mapValues { (e, t) -> (kotlin.math.ln(t / 100.0) - hinnang.logKeskmine[e]!!) / hinnang.logSd[e]!! }
    vaatlused.getOrPut(v.aasta) { mutableListOf() }.add(vead)
  }
  val püsivad = vaatlused.values.flatten().flatMap { it.keys }.groupingBy { it }.eachCount()
    .filter { (e, _) -> vaatlused.count { (_, l) -> l.any { e in it } } >= 3 }.keys.sorted()
  var sõltumatu = 0.0
  var korreleeritud = 0.0
  var hinnatud = 0
  for ((aasta, vead) in vaatlused) {
    val r = korrelatsioonid(vaatlused.filterKeys { it != aasta }.values.flatten(), püsivad)
    for (v in vead) {
      val erakonnad = püsivad.filter { it in v }
      if (erakonnad.size < 2) continue
      val z = DoubleArray(erakonnad.size) { v[erakonnad[it]]!! }
      val idx = erakonnad.map { püsivad.indexOf(it) }
      val alam = Array(erakonnad.size) { i -> DoubleArray(erakonnad.size) { j -> r[idx[i]][idx[j]] } }
      val ühik = Array(erakonnad.size) { i -> DoubleArray(erakonnad.size) { j -> if (i == j) 1.0 else 0.0 } }
      val lk = logTihedus(z, alam) ?: continue
      sõltumatu += logTihedus(z, ühik)!!
      korreleeritud += lk
      hinnatud += 1
    }
  }
  val korrelatsioonidKehtivad = hinnatud > 0 && korreleeritud > sõltumatu
  r.appendLine("- Correlations between parties' errors (parties in at least three elections: ${püsivad.joinToString(", ")}), " +
    "leave-one-out log score over $hinnatud forecasts: ${f(korreleeritud)} with correlations against ${f(sõltumatu)} " +
    "with independent errors. Correlations are " + (if (korrelatsioonidKehtivad) "adopted." else "not adopted."))
  r.appendLine()

  // suurimad erinevused: näitab, millised vead dispersioonihinnanguid mõjutavad
  r.appendLine("## Largest pollster errors")
  r.appendLine()
  r.appendLine("The five largest differences (log of a pollster's mean minus log of the result) at each horizon. The")
  r.appendLine("variance estimates average squares, so a few large differences can dominate them.")
  r.appendLine()
  r.appendLine("| Horizon | Election | Party | Pollster | Pollster mean | Result | Difference |")
  r.appendLine("|---|---|---|---|---|---|---|")
  for (h in HORISONDID) {
    val erinevused = valimised.flatMap { v ->
      val t = v.kuupäev.minusDays(h)
      val valitudKüsitlused = valiKüsitlused(v.küsitlused, t)
      v.tulemus.filter { it.value >= HINNATAVA_PIIR }.flatMap { (e, tul) ->
        valitudKüsitlused.groupBy { it.küsitleja }.values.mapNotNull { küsitlejaHinnang(it, e, t) }
          .map { listOf(v.aasta, e, it.küsitleja, kotlin.math.exp(it.logKeskmine) * 100, tul, it.logKeskmine - kotlin.math.ln(tul / 100.0)) }
      }
    }.sortedByDescending { kotlin.math.abs(it[5] as Double) }.take(5)
    for (x in erinevused) {
      r.appendLine("| $h d | ${x[0]} | ${x[1]} | ${x[2]} | ${f(x[3] as Double, 1)}% | ${f(x[4] as Double, 1)}% | ${f(x[5] as Double)} |")
    }
  }
  r.appendLine()

  // lõplikud parameetrid kõigist valimistest
  val lõplik = HORISONDID.associateWith { hindaParameetrid(valimised, it) }
  r.appendLine("## Final parameters (all elections)")
  r.appendLine()
  r.appendLine("| Horizon | Common error | House effect (pooled) | House effect by pollster |")
  r.appendLine("|---|---|---|---|")
  for ((h, p) in lõplik) {
    val küsitlejad = p.küsitlejateMajaefekt.entries.sortedBy { it.key }.joinToString(", ") { "${it.key} ${f(sqrt(it.value))}" }
    r.appendLine("| $h d | ${f(sqrt(p.ühine))} | ${f(sqrt(p.majaefekt))} | $küsitlejad |")
  }
  r.appendLine()

  // 2023. aasta mandaatide kontroll (üks andmepunkt)
  if (lugeja != null && valimised.any { it.aasta == 2023 }) {
    val mudel = Koondmudel(valitud, vigaKehtib, lõplik)
    r.append(mandaatideKontroll2023(lugeja, mudel))
  }

  val json = StringBuilder()
  json.appendLine("{")
  json.appendLine("  \"meetod\": \"${valitud.name}\",")
  json.appendLine("  \"veamudelKehtib\": $vigaKehtib,")
  json.appendLine("  \"korrelatsioonidKehtivad\": $korrelatsioonidKehtivad,")
  json.appendLine("  \"horisondid\": {")
  json.appendLine(lõplik.entries.joinToString(",\n") { (h, p) ->
    "    \"$h\": {\"ühine\": ${p.ühine}, \"majaefekt\": ${p.majaefekt}, \"küsitlejad\": {" +
      p.küsitlejateMajaefekt.entries.sortedBy { it.key }.joinToString(", ") { "\"${it.key}\": ${it.value}" } + "}}"
  })
  json.appendLine("  }")
  json.appendLine("}")
  return Tagasitest(r.toString(), json.toString())
}


/**
 * Mandaatide kontroll 2023. aasta valimistel: 1000 kordust viimase Norstati küsitluse ja küsitluste koondi
 * põhjal, kumbki oma küsitluse veaga, ning nende vahemike võrdlus tegelike mandaatidega. Parameetrid on
 * hinnatud ka 2023. aasta andmetest, seega on see üks andmepunkt, mitte kalibreerimise tõend.
 */
fun mandaatideKontroll2023(lugeja: AndmeFailideLugeja, mudel: Koondmudel): String {
  val r = StringBuilder()
  val kandidaadid = lugeja.loeKandidaadikirjed()
  val tegelik = andmed.loeRk2023Tulemus(lugeja.loeRessurss(andmed.RK2023_TULEMUSE_FAIL)).kandidaadid
    .filter { it.mandaat != null }.groupingBy { it.erakond }.eachCount()
  val norstat = andmed.reitingudToetusprotsentidena(andmed.loeReitingud(lugeja.loeRessurss("reitingud/reitingud-2023-03-03.json")))
  val (koond, küsitlejad) = andmed.koond2023(lugeja, mudel)
  val andmestikud = listOf(
    Triple("last Norstat poll (3 Mar)", norstat, mudel.viga(listOf("Norstat"), andmed.horisont(java.time.LocalDate.parse("2023-03-03")))),
    Triple("poll aggregate (3 Mar)", koond, mudel.viga(küsitlejad, andmed.horisont(andmed.KOONDI_KUUPÄEV))),
  )
  r.appendLine("## Seat check for 2023 (one data point)")
  r.appendLine()
  r.appendLine("1000 runs with seed 1 for each data set, with its own poll error; the parameters were estimated with")
  r.appendLine("2023 included, so this is a sanity check, not evidence of calibration.")
  r.appendLine()
  for ((nimi, toetus, viga) in andmestikud) {
    val k = simuleeriKorduvalt(kandidaadid, toetus, 1000, kotlin.random.Random(1), viga = viga)
    r.appendLine("### ${nimi.replaceFirstChar { it.uppercase() }}: national error ${f(viga.üleriigiline, 3)}, district error ${f(viga.ringkondlik, 3)}")
    r.appendLine()
    r.appendLine("| Party | Actual seats | Mean | 90% range | Inside |")
    r.appendLine("|---|---|---|---|---|")
    var sees = 0
    val erakonnad = (tegelik.keys + k.erakondadeMandaadid.keys).distinct().sortedByDescending { tegelik[it] ?: 0 }
    for (e in erakonnad) {
      val m = (k.erakondadeMandaadid[e] ?: List(k.kordi) { 0 }).sorted()
      val p05 = m[(0.05 * m.size).toInt().coerceAtMost(m.size - 1)]
      val p95 = m[(kotlin.math.ceil(0.95 * m.size).toInt() - 1).coerceAtMost(m.size - 1)]
      val t = tegelik[e] ?: 0
      val ok = t in p05..p95
      if (ok) sees += 1
      r.appendLine("| $e | $t | ${f(m.average(), 1)} | $p05–$p95 | ${if (ok) "yes" else "no"} |")
    }
    r.appendLine()
    r.appendLine("Inside the 90% range: $sees of ${erakonnad.size} parties.")
    r.appendLine()
  }
  return r.toString()
}
